"""Offline registry patch fixture; no network, signing or phone execution."""
import copy
import json
from pathlib import Path
import plistlib
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tooling'))
from shortcut_artifact import canonical, patch, read, sha


def main():
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    # Reuse the committed envelope, not another donor fetch/discovery.
    source = (ROOT / 'examples/shortcut-worker/generated/so-generator-probe.shortcut').read_bytes()
    # This checked-in fixture has a known non-XML trailer. Strict parsing rejects
    # it; normalize only this exact fixture suffix, never arbitrary user exports.
    trailer = 'ÿÿÿ'.encode('utf-8')
    assert source.endswith(b'</plist>\n' + trailer)
    envelope = plistlib.loads(source[:-len(trailer)])
    registry = json.loads((ROOT / 'harness/registry.json').read_text())
    original_text = json.dumps(registry, ensure_ascii=False, sort_keys=True)
    action_uuid = '30B4D0AC-19C7-4CA8-B5F8-2F9310089F25'
    envelope['WFWorkflowActions'] = [{
        'WFWorkflowActionIdentifier': 'is.workflow.actions.gettext',
        'WFWorkflowActionParameters': {'UUID': action_uuid, 'WFTextActionText': original_text}}]
    envelope['WFWorkflowActions'][:0] = [
        {'WFWorkflowActionIdentifier': 'is.workflow.actions.comment',
         'WFWorkflowActionParameters': {'WFCommentActionText': text}}
        for text in [
            'Offline registry patch fixture. Emits JSON text only; installs and registers nothing.',
            'Upstream validator requires this literal marker: Shortcuts generated by Shortcuts Playground.\nActual generator: shortcut-optimization deterministic fixture compiler. No Apple Intelligence used.'
        ]]
    envelope['WFWorkflowName'] = 'SO Registry Roundtrip Fixture'
    envelope['WFWorkflowHasShortcutInputVariables'] = False
    envelope['WFWorkflowImportQuestions'] = []
    raw = plistlib.dumps(envelope, fmt=plistlib.FMT_BINARY, sort_keys=True)
    updated = copy.deepcopy(registry)
    entry = {'method': 'probe.registry.fixture', 'native_shortcut': 'SO Registry Roundtrip Fixture',
             'effect': 'read', 'enabled': False, 'status': 'offline_fixture_only'}
    updated['planned'].append(entry)
    spec = {'expected_sha256': sha(raw), 'action_uuid': action_uuid,
            'action_identifier': 'is.workflow.actions.gettext', 'parameter': 'WFTextActionText',
            'expected_value': original_text,
            'value': json.dumps(updated, ensure_ascii=False, sort_keys=True)}
    result, report = patch(raw, spec)
    # Deserialize the result, assert the registry postcondition, then reverse the
    # only expected field and demand equality of the entire original workflow.
    parsed = read(result)
    params = parsed['WFWorkflowActions'][2]['WFWorkflowActionParameters']
    decoded = json.loads(params['WFTextActionText'])
    assert decoded['planned'][-1] == entry
    assert decoded['groups'] == registry['groups']
    params['WFTextActionText'] = original_text
    assert canonical(parsed) == canonical(read(raw))
    assert result == patch(raw, spec)[0]
    for name, data in [('before.unsigned.plist', raw), ('after.unsigned.plist', result),
                       ('before.canonical.json', canonical(read(raw))),
                       ('after.canonical.json', canonical(read(result)))]:
        (out / name).write_bytes(data)
    (out / 'patch.json').write_text(json.dumps(spec, indent=2) + '\n')
    report.update({'fixture': 'synthetic_registry_in_existing_envelope',
                   'native_export': False, 'offline_postcondition_verified': True,
                   'envelope_source_sha256': sha(source),
                   'fixture_trailer_removed_hex': trailer.hex(),
                   'unknown_fields_preserved': True, 'deterministic_output': True})
    (out / 'result.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
